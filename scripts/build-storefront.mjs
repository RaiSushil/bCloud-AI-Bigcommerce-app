/**
 * Builds the storefront JavaScript from storefront/src into public/storefront (minified), plus
 * the module the admin's Storefront design preview runs. Run after changing any file in
 * storefront/src or storefront/bcloud.css:  npm run build:storefront
 *
 * Only the core is loaded first; every other module is loaded by the core when a page needs it.
 * Shared helpers (storefront/src/lib.js: product cards, icons, lists) are bundled into each module.
 * The files in public/storefront are what the app's Script Manager scripts load on the storefront
 * (served by this app at APP_URL/storefront/…?v=STOREFRONT_VERSION).
 */
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";

const OUT = "public/storefront";
mkdirSync(OUT, { recursive: true });
copyFileSync("storefront/bcloud.css", `${OUT}/bcloud.css`);
const MODULES = {
  bcloud: "core.js", // loaded on every page: keep it small (under 10 KB)
  "bcloud-search": "search.js",
  "bcloud-rails": "rails.js",
  "bcloud-autocomplete": "autocomplete.js",
  "bcloud-image": "image.js",
  "bcloud-chat": "chat.js",
  "bcloud-commerce": "commerce.js", // storefront only: product views and add to cart
  "bcloud-purchase": "purchase.js", // order confirmation page only (its own Script Manager script)
};
const PREVIEW_MODULES = ["bcloud", "bcloud-search", "bcloud-rails", "bcloud-autocomplete", "bcloud-image", "bcloud-chat"];
const CORE_LIMIT = 10_000;

for (const [name, file] of Object.entries(MODULES)) {
  await build({
    entryPoints: [`storefront/src/${file}`],
    outfile: `${OUT}/${name}.js`,
    bundle: true,
    format: "iife",
    minify: true,
    target: "es2018",
    legalComments: "none",
    banner: { js: `/* bCloud AI Search. Built from storefront/src/${file}; edit the source, not this file. */` },
    logLevel: "warning",
  });
  const size = statSync(`${OUT}/${name}.js`).size;
  console.log(`${`${name}.js`.padEnd(26)} ${String(size).padStart(6)} B`);
  if (name === "bcloud" && size > CORE_LIMIT) {
    console.error(`bcloud.js is ${size} B; keep it under ${CORE_LIMIT} B (move code into a module).`);
    process.exit(1);
  }
}

// The admin's Storefront design preview runs these same files, from a module under app/.
const read = (f) => readFileSync(f, "utf8");
const PREVIEW = "app/portal/pages/storefront-design/storefront-assets.generated.ts";
const assets = Object.fromEntries(
  PREVIEW_MODULES.map((name) => [name === "bcloud" ? "core" : name.replace(/^bcloud-/, ""), read(`${OUT}/${name}.js`)]),
);
// One version for every storefront file: the Script Manager scripts load ?v=<version>, and the
// Storefront page shows "Update" when the installed scripts were made from an older build.
const hash = createHash("sha256");
for (const name of Object.keys(MODULES)) hash.update(read(`${OUT}/${name}.js`));
hash.update(read("storefront/bcloud.css"));
hash.update(read("storefront/locales/en.default.json"));
const version = hash.digest("hex").slice(0, 12);
writeFileSync(
  PREVIEW,
  `/* Generated by scripts/build-storefront.mjs from storefront/. Do not edit; run npm run build:storefront. */\n` +
    `export const STOREFRONT_JS: Record<"core" | "search" | "rails" | "autocomplete" | "image" | "chat", string> = ${JSON.stringify(assets)};\n` +
    `export const STOREFRONT_CSS: string = ${JSON.stringify(read("storefront/bcloud.css"))};\n` +
    `export const STOREFRONT_LOCALE: string = ${JSON.stringify(read("storefront/locales/en.default.json"))};\n` +
    `export const STOREFRONT_VERSION: string = ${JSON.stringify(version)};\n`,
);
console.log(`${PREVIEW.split("/").pop().padEnd(26)} ${String(statSync(PREVIEW).size).padStart(6)} B`);

